export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, bn };

const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function localizeDigits(input: string | number, lang: Lang): string {
  const s = String(input);
  return lang === "bn" ? s.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]) : s;
}

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, typeof v === "number" ? localizeDigits(v, lang) : v);
    }
  }
  return s;
}
